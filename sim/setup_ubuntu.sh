#!/usr/bin/env bash
# One-shot environment setup for the brick_sim pipeline on Ubuntu + RTX 5090 (Blackwell, needs CUDA 12.8 wheels).
# Usage:  bash setup_ubuntu.sh            (creates ./venv, installs torch cu128 + lerobot + mujoco, fetches SO-ARM100)
set -euo pipefail
cd "$(dirname "$0")"

PY=${PYTHON:-python3}
$PY --version
if [ ! -d venv ]; then $PY -m venv venv; fi
source venv/bin/activate
pip install -U pip wheel

# RTX 5090 = sm_120 -> torch >= 2.7 built for CUDA 12.8
pip install --index-url https://download.pytorch.org/whl/cu128 torch torchvision torchcodec
pip install "lerobot>=0.6" mujoco av numpy pillow opencv-python   # opencv: brick_sim/perception.py (RQ4 camera gate)

# system libs for EGL headless rendering (skip if already present)
if command -v apt-get >/dev/null 2>&1; then
  sudo apt-get install -y libegl1 libgl1 libglib2.0-0 ffmpeg 2>/dev/null || true
fi

# SO-ARM100 model from MuJoCo Menagerie (sparse checkout)
if [ ! -d menagerie/trs_so_arm100 ]; then
  git clone --depth 1 --filter=blob:none --sparse https://github.com/google-deepmind/mujoco_menagerie.git menagerie
  (cd menagerie && git sparse-checkout set trs_so_arm100)
fi
rm -f menagerie/trs_so_arm100/so_arm100_tcp.xml   # regenerated by scene.py on first run

export MUJOCO_GL=egl
python - <<'EOF'
import torch, mujoco, lerobot
print("torch", torch.__version__, "cuda", torch.cuda.is_available(), torch.cuda.get_device_name(0) if torch.cuda.is_available() else "-")
print("mujoco", mujoco.__version__, "lerobot", lerobot.__version__)
EOF
python run_expert_eval.py --task 2p1 --mortar dry --seeds 2 --pos-rand 0.005 | grep -E "seed=|blueprint"
echo "setup OK. Next: bash run_phase1.sh"
